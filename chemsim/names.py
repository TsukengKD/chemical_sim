def parse_formula(formula: str) -> dict:
    """'NaCl' -> {'Na': 1, 'Cl': 1}.  Скобки не поддерживаются."""
    counts: dict = {}
    for sym, n in re.findall(r"([A-Z][a-z]?)(\d*)", formula):
        counts[sym] = counts.get(sym, 0) + (int(n) if n else 1)
    return counts


def hill_formula(counts: dict) -> str:
    """Формула в системе Хилла: C, H, затем остальные по алфавиту."""
    parts = []
    keys = list(counts.keys())
    if "C" in counts:
        order = ["C"] + (["H"] if "H" in counts else []) + sorted(k for k in keys if k not in ("C", "H"))
    else:
        order = sorted(keys)
    for k in order:
        n = counts[k]
        parts.append(k if n == 1 else f"{k}{n}")
    return "".join(parts)



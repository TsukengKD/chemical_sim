def display_formula(counts: dict) -> str:
    """Привычная запись: органика — по Хиллу, неорганика — по возрастанию
    электроотрицательности (как NaCl, H2O, CO2), с исключениями (NH3, NaOH…)."""
    hill = hill_formula(counts)
    if hill in _DISPLAY_OVERRIDES:
        return _DISPLAY_OVERRIDES[hill]
    if "C" in counts and len(counts) > 1:
        return hill
    from .elements import ELEMENTS
    order = sorted(counts, key=lambda k: (ELEMENTS[k].chi if ELEMENTS[k].chi > 0 else 9, k))
    return "".join(k if counts[k] == 1 else f"{k}{counts[k]}" for k in order)


def pretty_formula(formula: str) -> str:
    """Формула с подстрочными цифрами Юникода (H₂O)."""
    sub = str.maketrans("0123456789", "₀₁₂₃₄₅₆₇₈₉")
    return formula.translate(sub)


NAMES = {hill_formula(parse_formula(k)): v for k, v in _NAMES_CONV.items()}


def species_name(hill: str) -> str | None:
    """Название по формуле Хилла (или None)."""
    return NAMES.get(hill)

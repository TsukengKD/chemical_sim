"""Готовые опыты: только НАЧАЛЬНЫЕ условия (что и сколько положить в реактор,
какая температура стенок).  Чем закончится опыт, определяет физика."""

from __future__ import annotations

from dataclasses import dataclass, field

from .molecules import place
from .simulation import Simulation, WALLS, ISOLATED


@dataclass
class Scenario:
    key: str
    title: str
    description: str
    reagents: list                    # [(формула, количество), ...]
    temperature: float = 300.0        # начальная температура газа и стенок, К
    mode: str = WALLS
    box: tuple = (60.0, 40.0, 8.0)
    hint: str = ""
    extra: dict = field(default_factory=dict)

    def apply(self, sim: Simulation):
        sim.clear()
        sim.set_box(self.box)
        sim.set_mode(self.mode)
        sim.set_temperature(self.temperature)
        placed = []
        for formula, count in self.reagents:
            placed.append((formula, place(sim, formula, count, temperature=self.temperature)))
        return placed



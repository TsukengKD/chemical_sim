def _normalize(table):
    out = {}
    for (a, b, n), val in table.items():
        key = (min(a, b), max(a, b), n)
        out[key] = val
    return out


BOND_TABLE = _normalize(_RAW)


def lookup(a: str, b: str, order: int):
    """Вернуть (D, r) из таблицы или None."""
    return BOND_TABLE.get((min(a, b), max(a, b), order))
